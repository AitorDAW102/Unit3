public class WP4 {
    public static void main(String[] args) {
        for (int i=1; i<=10; i++){
            System.out.println("TABLA DEL NUMERO "+i);
            for (int x=1; x<=10; x++){
                System.out.println(i+"*"+x+"="+i*x);
            }
            System.out.println();
        }
    }
}
